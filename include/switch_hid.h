#pragma once

#include <stdint.h>

typedef struct __attribute__((packed)) {
    uint16_t buttons;
    uint8_t hat;
    uint8_t lx;
    uint8_t ly;
    uint8_t rx;
    uint8_t ry;
    uint8_t vendor;
} C7sPadReport;

typedef struct __attribute__((packed)) {
    uint8_t modifier;
    uint8_t reserved;
    uint8_t keycode[6];
} C7sKbdReport;

#define SWITCH_HAT_UP        0x00
#define SWITCH_HAT_UPRIGHT   0x07
#define SWITCH_HAT_RIGHT     0x06
#define SWITCH_HAT_DOWNRIGHT 0x05
#define SWITCH_HAT_DOWN      0x04
#define SWITCH_HAT_DOWNLEFT  0x03
#define SWITCH_HAT_LEFT      0x02
#define SWITCH_HAT_UPLEFT    0x01
#define SWITCH_HAT_NOTHING   0x08

#define SWITCH_BTN_Y        (1u << 0)
#define SWITCH_BTN_B        (1u << 1)
#define SWITCH_BTN_A        (1u << 2)
#define SWITCH_BTN_X        (1u << 3)
#define SWITCH_BTN_L        (1u << 4)
#define SWITCH_BTN_R        (1u << 5)
#define SWITCH_BTN_ZL       (1u << 6)
#define SWITCH_BTN_ZR       (1u << 7)
#define SWITCH_BTN_MINUS    (1u << 8)
#define SWITCH_BTN_PLUS     (1u << 9)
#define SWITCH_BTN_L3       (1u << 10)
#define SWITCH_BTN_R3       (1u << 11)
#define SWITCH_BTN_HOME     (1u << 12)
#define SWITCH_BTN_CAPTURE  (1u << 13)

#define SWITCH_STICK_MIN 0x00
#define SWITCH_STICK_MID 0x80
#define SWITCH_STICK_MAX 0xFF

